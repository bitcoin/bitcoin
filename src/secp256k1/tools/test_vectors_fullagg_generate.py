#!/usr/bin/env python3

import csv
import os
import sys

if len(sys.argv) < 2:
    print(
        "This script converts BIP FullAgg test vectors in a given directory to a C file that can be used in the test framework."
    )
    print("Usage: %s <dir>" % sys.argv[0])
    sys.exit(1)


def read_csv(filename):
    with open(os.path.join(sys.argv[1], filename), newline="") as f:
        rows = list(csv.reader(f))
    return rows[1:]


def hexstr_to_intarray(s):
    return ", ".join([f"0x{b:02X}" for b in bytes.fromhex(s)])


def hexlist(s):
    return s.split(";") if s else []


def init_int(value, indent):
    return indent * " " + "%d" % value


def init_array(s, indent):
    return indent * " " + "{ %s }" % hexstr_to_intarray(s)


def init_arrays(strs, indent):
    out = indent * " " + "{\n"
    out += ",\n".join([init_array(x, indent + 4) for x in strs])
    out += "\n" + indent * " " + "}"
    return out


def init_case(comment, fields):
    out = "    /* %s */\n" % comment
    out += "    {\n"
    out += ",\n".join(fields)
    out += "\n    },\n"
    return out


max_signers = 0

s = (
    """/**
 * Automatically generated by %s. */
"""
    % sys.argv[0]
)

# sign vectors
rows = read_csv("test_vectors_sign.csv")
n = max(len(hexlist(row[1])) for row in rows)
max_signers = max(max_signers, n)
s += """
struct fullagg_sign_case {
    size_t n_signers;
    unsigned char sks[%d][32];
    unsigned char msgs[%d][32];
    unsigned char secnonces[%d][64];
    unsigned char expected_aggnonce[66];
    unsigned char expected_psigs[%d][32];
    unsigned char expected_sig[64];
};

static const struct fullagg_sign_case fullagg_sign_cases[%d] = {
""" % (n, n, n, n, len(rows))
for row in rows:
    _, sks, msgs, secnonces, aggnonce, psigs, sig, comment = row
    s += init_case(comment, [
        init_int(len(hexlist(sks)), 8),
        init_arrays(hexlist(sks), 8),
        init_arrays(hexlist(msgs), 8),
        init_arrays(hexlist(secnonces), 8),
        init_array(aggnonce, 8),
        init_arrays(hexlist(psigs), 8),
        init_array(sig, 8),
    ])
s += "};\n"

# sign error vectors
rows = read_csv("test_vectors_sign_error.csv")
n = max(len(hexlist(row[4])) for row in rows)
max_signers = max(max_signers, n)
s += """
struct fullagg_sign_error_case {
    unsigned char sk[32];
    unsigned char msg[32];
    unsigned char secnonce[64];
    size_t n_signers;
    unsigned char pubkeys[%d][32];
    unsigned char msgs[%d][32];
    unsigned char pubnonces[%d][66];
};

static const struct fullagg_sign_error_case fullagg_sign_error_cases[%d] = {
""" % (n, n, n, len(rows))
for row in rows:
    _, sk, msg, secnonce, pubkeys, msgs, pubnonces, comment = row
    s += init_case(comment, [
        init_array(sk, 8),
        init_array(msg, 8),
        init_array(secnonce, 8),
        init_int(len(hexlist(pubkeys)), 8),
        init_arrays(hexlist(pubkeys), 8),
        init_arrays(hexlist(msgs), 8),
        init_arrays(hexlist(pubnonces), 8),
    ])
s += "};\n"

# verify vectors. The cases with signatures whose length is not 64 bytes,
# with lists of different lengths and with an empty signer list are omitted
# because they cannot be expressed through the C API.
rows = [
    row for row in read_csv("test_vectors_verify.csv")
    if len(row[3]) == 128
    and len(hexlist(row[1])) == len(hexlist(row[2]))
    and len(hexlist(row[1])) > 0
]
n = max(len(hexlist(row[1])) for row in rows)
max_signers = max(max_signers, n)
s += """
/* The verify vectors whose inputs cannot be expressed through the C API are
 * omitted (signatures whose length is not 64 bytes, lists of different
 * lengths and empty signer lists). */
struct fullagg_verify_case {
    size_t n_signers;
    unsigned char pubkeys[%d][32];
    unsigned char msgs[%d][32];
    unsigned char sig[64];
    int expected;
};

static const struct fullagg_verify_case fullagg_verify_cases[%d] = {
""" % (n, n, len(rows))
for row in rows:
    _, pubkeys, msgs, sig, expected, comment = row
    s += init_case(comment, [
        init_int(len(hexlist(pubkeys)), 8),
        init_arrays(hexlist(pubkeys), 8),
        init_arrays(hexlist(msgs), 8),
        init_array(sig, 8),
        init_int(int(expected == "TRUE"), 8),
    ])
s += "};\n"

# partial signature verify vectors
rows = read_csv("test_vectors_partial_sig_verify.csv")
n = max(len(hexlist(row[3])) for row in rows)
max_signers = max(max_signers, n)
s += """
struct fullagg_partial_sig_verify_case {
    size_t signer_index;
    unsigned char psig[32];
    size_t n_signers;
    unsigned char pubkeys[%d][32];
    unsigned char msgs[%d][32];
    unsigned char pubnonces[%d][66];
    int expected;
};

static const struct fullagg_partial_sig_verify_case fullagg_partial_sig_verify_cases[%d] = {
""" % (n, n, n, len(rows))
for row in rows:
    _, signer_index, psig, pubkeys, msgs, pubnonces, expected, comment = row
    s += init_case(comment, [
        init_int(int(signer_index), 8),
        init_array(psig, 8),
        init_int(len(hexlist(pubkeys)), 8),
        init_arrays(hexlist(pubkeys), 8),
        init_arrays(hexlist(msgs), 8),
        init_arrays(hexlist(pubnonces), 8),
        init_int(int(expected == "TRUE"), 8),
    ])
s += "};\n"

# tweak vectors
rows = read_csv("test_vectors_tweak.csv")
s += """
struct fullagg_tweak_case {
    unsigned char sk[32];
    unsigned char tweak[32];
    int is_xonly;
    int expected;
    unsigned char expected_sk[32];
    unsigned char expected_pk[33];
};

static const struct fullagg_tweak_case fullagg_tweak_cases[%d] = {
""" % len(rows)
for row in rows:
    _, sk, tweak, is_xonly, expected, expected_sk, expected_pk, comment = row
    s += init_case(comment, [
        init_array(sk, 8),
        init_array(tweak, 8),
        init_int(int(is_xonly == "TRUE"), 8),
        init_int(int(expected == "TRUE"), 8),
        init_array(expected_sk or "00", 8),
        init_array(expected_pk or "00", 8),
    ])
s += "};\n"

s += "\nenum { FULLAGG_VECTORS_MAX_SIGNERS = %d };" % max_signers
print(s)
